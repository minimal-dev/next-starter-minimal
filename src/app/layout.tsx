import type { ReactNode } from 'react'
import { Epilogue } from 'next/font/google'

import Header from '~components/Header'
import Footer from '~components/Footer'

import 'modern-normalize/modern-normalize.css'
import '../styles/app.scss'

// Example of using google font
// For local fonts follow: https://nextjs.org/docs/app/getting-started/fonts

const epilogue = Epilogue({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-body',
})

export const metadata = {
  // Absolute base for OG/Twitter image URLs. SITE_URL wins; Vercel sets the
  // production domain automatically.
  metadataBase: new URL(
    process.env.SITE_URL ??
      (process.env.VERCEL_PROJECT_PRODUCTION_URL
        ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
        : 'http://localhost:3000')
  ),
  title: {
    template: '%s | Minimal Next Starter',
    default: 'Minimal Next Starter',
  },
  description: 'Generated by create next app',
  openGraph: {
    locale: 'en-US',
    type: 'website',
  },
  twitter: {
    card: 'summary_large_image',
  },
}

export const viewport = {
  themeColor: '#000000',
}

const RootLayout = ({ children }: { children: ReactNode }) => {
  return (
    <html lang="en">
      <body className={epilogue.variable} style={{ minWidth: 360 }}>
        <Header title={metadata.title?.default} />
        <main className="main">{children}</main>
        <Footer title={metadata.title?.default} />
      </body>
    </html>
  )
}

export default RootLayout
